const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'xochitl/herdRespond.qmd'),'utf8');
const start=source.indexOf('function herdSetDisplayAwake(');
const end=source.indexOf('\n\t\t\t\tproperty ',start);
const calls=[];
const ctx=vm.createContext({root:{inSuspend:false},BatteryManager:{onActivity(){calls.push('activity');}},console:{warn(){}}});
vm.runInContext(source.slice(start,end),ctx);
ctx.herdSetDisplayAwake(true);ctx.herdSetDisplayAwake(true);
assert.deepEqual(calls,['activity','activity'],'explicit maintenance refreshes the actual native activity timer');
ctx.herdSetDisplayAwake(false);assert.equal(calls.length,2,'disarm does not emit activity');
ctx.root.inSuspend=true;ctx.herdSetDisplayAwake(true);assert.equal(calls.length,2,'never override intentional sleep');
ctx.root.inSuspend=false;delete ctx.BatteryManager.onActivity;ctx.herdSetDisplayAwake(true);assert.equal(calls.length,2);
assert(source.includes('interval: 90000; repeat: true'));
assert(source.includes('running: herdButton.herdAwakeActive'));
assert(!source.includes('Settings.idleSuspendDelay ='),'no persistent power setting');
console.log('Native display wake: bounded native activity heartbeat, no synthetic input, disarm/suspend guards, no persistent setting passed.');
